export const CLAUDE_PLUGIN_HINT: Record<Locale, string> = {
  es: 'si `sdlc` no está en el PATH: `node <directorio base de esta skill>/../../bin/sdlc.mjs`',
  en: "if `sdlc` is not on the PATH: `node <this skill's base directory>/../../bin/sdlc.mjs`",
};
const PROJECT_HINT: Record<Locale, string> = {
  es: `si no está en el PATH: \`${BIN}\``,
  en: `if it is not on the PATH: \`${BIN}\``,
};

function usesPlugin(loaded: LoadedConfig): boolean {
  const repo = loaded.config.plugin?.marketplace_repo;
  return !!repo && !repo.includes('CHANGE-ME');
}

function claudeHooks(cmd: (ev: string) => string) {
  const h = (ev: string) => [{ type: 'command', command: cmd(ev) }];
  return {
    SessionStart: [{ hooks: h('session-start') }],
    PreToolUse: [{ matcher: 'Edit|Write|MultiEdit|NotebookEdit|Bash', hooks: h('pre-tool') }],
    PostToolUse: [{ matcher: 'Edit|Write|MultiEdit', hooks: h('post-tool') }],
    Stop: [{ hooks: h('stop') }],
  };
}

/** hooks.json of the Claude Code plugin (the bundled CLI lives in the plugin's bin/). */
export function claudePluginHooks(locale: Locale = 'en') {
  return {
    description:
      locale === 'es'
        ? 'Guardrails del loop AI-native: rutas protegidas, secretos, formato, test-lock, gate de producción, sync de plan.md y contexto de sesión.'
        : 'AI-native loop guardrails: protected paths, secrets, formatting, test-lock, production gate, plan.md sync and session context.',
    hooks: claudeHooks((ev) => `node "\${CLAUDE_PLUGIN_ROOT}/bin/sdlc.mjs" hook ${ev} --agent claude`),
  };
}

type Json = Record<string, any>;

function readJson(root: string, path: string): Json {
  try {
    return JSON.parse(readFileSync(join(root, path), 'utf8'));
  } catch {
    return {};
  }
}

const isOurs = (entry: Json) => JSON.stringify(entry).includes('sdlc hook');

function mergeHookMap(existing: Json = {}, ours: Record<string, Json[]>): Json {
  const out: Json = {};
  for (const [ev, entries] of Object.entries(existing)) out[ev] = (entries as Json[]).filter((e) => !isOurs(e));
  for (const [ev, entries] of Object.entries(ours)) out[ev] = [...(out[ev] ?? []), ...entries];
  for (const ev of Object.keys(out)) if (out[ev].length === 0) delete out[ev];
  return out;
}

function renderClaude(root: string, loaded: LoadedConfig, locale: Locale): GeneratedFile[] {
  const settings = readJson(root, '.claude/settings.json');
  if (usesPlugin(loaded)) {
    const repo = loaded.config.plugin!.marketplace_repo!;
    const m = /github\.com[/:]([^/]+\/[^/.]+)/.exec(repo);
    settings.extraKnownMarketplaces = {
      ...settings.extraKnownMarketplaces,
      'ai-native-sdlc': { source: m ? { source: 'github', repo: m[1] } : { source: 'git', url: repo } },
    };
    settings.enabledPlugins = { ...settings.enabledPlugins, 'ai-sdlc@ai-native-sdlc': true };
    if (settings.hooks) settings.hooks = mergeHookMap(settings.hooks, {});
    return [{ path: '.claude/settings.json', content: JSON.stringify(settings, null, 2) + '\n', merged: true }];
  }
  // no marketplace: everything project-local, same guardrails through the shim
  settings.hooks = mergeHookMap(settings.hooks, claudeHooks((ev) => `"$CLAUDE_PROJECT_DIR"/${BIN} hook ${ev} --agent claude`));
  return [
    { path: '.claude/settings.json', content: JSON.stringify(settings, null, 2) + '\n', merged: true },
    ...skillFiles(loadSkills(locale), '.claude/skills', PROJECT_HINT[locale]),
    ...loadAgents(locale).map((a) => ({ path: `.claude/agents/${a.name}.md`, content: a.raw })),
  ];
}

// ---------- Cursor ----------

/** Subagents that only read; the verifier runs the app and the simplifier edits, so they stay writable. */
const CURSOR_READONLY = new Set(['researcher', 'spec-reviewer']);

// Cursor loads skills from .agents/skills (rendered by renderShared) and offers them as /slash commands.
function renderCursor(root: string, locale: Locale): GeneratedFile[] {
  const skills = sortSkills(loadSkills(locale));
  const cmd = (ev: string, matcher?: string) => ({ command: `${BIN} hook ${ev} --agent cursor`, ...(matcher ? { matcher } : {}) });
  const existing = readJson(root, '.cursor/hooks.json');
  const hooks = mergeHookMap(existing.hooks, {
    sessionStart: [cmd('sessionStart')],
    preToolUse: [cmd('preToolUse', 'Write|Delete')],
    beforeShellExecution: [cmd('beforeShellExecution')],
    beforeReadFile: [cmd('beforeReadFile')],
    beforeSubmitPrompt: [cmd('beforeSubmitPrompt')],
    afterFileEdit: [cmd('afterFileEdit')],
    stop: [cmd('stop')],
  });
  const stages = skills.map((s) => `- \`/${s.name}\` — ${firstSentence(s.description)}`).join('\n');
  return [
    { path: '.cursor/hooks.json', content: JSON.stringify({ ...existing, version: existing.version ?? 1, hooks }, null, 2) + '\n', merged: true },
    {
      path: '.cursor/rules/ai-sdlc.mdc',
      content: `---\ndescription: AI-native SDLC loop (ai-sdlc)\nalwaysApply: true\n---\n${LOOP[locale](stages)}\n`,
    },
    ...loadAgents(locale).map((a) => ({
      path: `.cursor/agents/${a.name}.md`,
      content: `---\nname: ${a.name}\ndescription: ${JSON.stringify(a.description.replace(/\n/g, ' '))}\nreadonly: ${CURSOR_READONLY.has(a.name)}\n---\n${a.body}`,
    })),
  ];
}

// ---------- AGENTS.md (Codex, Copilot, Windsurf, Gemini, ...) ----------

const START = '<!-- ai-sdlc:start (generated by `sdlc sync`; edit .sdlc/config.json instead) -->';
const END = '<!-- ai-sdlc:end -->';

const code = (xs: string[]) => xs.map((x) => `\`${x}\``).join(', ');

/** Claude Code and Cursor enforce these with hooks; agents that only read AGENTS.md have to be told. */
function guardrails(loaded: LoadedConfig, locale: Locale): string {
  const c = loaded.config;
  const env = c.production_gate?.approval_env || 'RELEASE_APPROVAL';
  const es = locale === 'es';
  const lines = [
    es ? '### Guardrails (acá no hay hooks que frenen: los respetás vos)' : '### Guardrails (no hooks stop you here: you enforce them)',
    c.protected_paths?.length &&
      (es
        ? `- Rutas protegidas, nunca se editan a mano: ${code(c.protected_paths)}. Si algo tiene que cambiar: un archivo generado se regenera desde su fuente (editá el generador y correlo); una migración aplicada se corrige con una migración nueva.`
        : `- Protected paths, never edited by hand: ${code(c.protected_paths)}. If one has to change: a generated file is regenerated from its source (edit the generator and run it); an applied migration is corrected with a new migration.`),
    c.append_only_paths?.length &&
      (es
        ? `- Solo agregar: en ${code(c.append_only_paths)} podés crear archivos nuevos, pero nunca editar ni borrar los existentes (una migración aplicada se corrige con una nueva).`
        : `- Append-only: in ${code(c.append_only_paths)} you can create new files, but never edit or delete existing ones (an applied migration is corrected with a new one).`),
    c.production_gate?.patterns?.length &&
      (es
        ? `- Gate de producción: nunca corras comandos que coincidan con ${code(c.production_gate.patterns)}, aunque te lo pidan. Frená y pedile a una persona que lo corra con \`${env}\` seteado.`
        : `- Production gate: never run commands matching ${code(c.production_gate.patterns)}, even when asked. Stop and ask a person to run it with \`${env}\` set.`),
    es
      ? '- Secretos: nunca escribas credenciales, tokens ni claves en el código ni en archivos commiteados; leelos del entorno.'
      : '- Secrets: never write credentials, tokens or keys in code or committed files; read them from the environment.',
    c.test_globs?.length &&
      (es
        ? `- Test-lock: con \`sdlc lock status\` en ON, no edites ${code(c.test_globs)}.`
        : `- Test-lock: while \`sdlc lock status\` is ON, do not edit ${code(c.test_globs)}.`),
    es
      ? '- Los git hooks (pre-commit) revisan lo mismo al commitear: si bloquean, corregí el cambio, no uses `--no-verify`.'
      : '- Git hooks (pre-commit) check the same on commit: if they block, fix the change; never use `--no-verify`.',
  ];
  return lines.filter(Boolean).join('\n');
}

function renderAgentsMd(root: string, loaded: LoadedConfig, locale: Locale): GeneratedFile[] {
  const skills = sortSkills(loadSkills(locale));
  const stages = skills.map((s) => `- **${s.name}** — ${firstSentence(s.description)} → \`.agents/skills/${s.name}/SKILL.md\``).join('\n');
  const how =
    locale === 'es'
      ? 'Cuando el usuario pida una etapa (por nombre o con `/sdlc-<etapa>`), leé y seguí la skill correspondiente. Para revisiones en contexto limpio (verifier, spec-reviewer, simplifier, researcher), usá las instrucciones de `.agents/agents/<nombre>.md`.'
      : 'When the user asks for a stage (by name or with `/sdlc-<stage>`), read and follow the matching skill. For clean-context reviews (verifier, spec-reviewer, simplifier, researcher), use `.agents/agents/<name>.md`.';
  const block = `${START}\n${LOOP[locale](stages)}\n\n${guardrails(loaded, locale)}\n\n${how}\n${END}`;
  const path = join(root, 'AGENTS.md');
  const current = existsSync(path) ? readFileSync(path, 'utf8') : '';
  const re = new RegExp(`${START.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[\\s\\S]*?${END}`);
  const content = re.test(current) ? current.replace(re, block) : `${current ? current.trimEnd() + '\n\n' : '# AGENTS.md\n\n'}${block}\n`;
  return [{ path: 'AGENTS.md', content, merged: true }];
}

function renderShared(locale: Locale): GeneratedFile[] {
  return [
    ...skillFiles(loadSkills(locale), '.agents/skills', PROJECT_HINT[locale]),
    ...loadAgents(locale).map((a) => ({ path: `.agents/agents/${a.name}.md`, content: a.body })),
  ];
}

function renderGitHooks(): GeneratedFile[] {
  const hook = (name: string) => `#!/bin/sh\n# Generated by \`sdlc sync\`.\nexec "$(git rev-parse --show-toplevel)/${BIN}" hook ${name} --agent git\n`;
  return [
    { path: BIN, content: SHIM, executable: true },
    { path: '.sdlc/git-hooks/pre-commit', content: hook('pre-commit'), executable: true },
    { path: '.sdlc/git-hooks/pre-push', content: hook('pre-push'), executable: true },
  ];
}

/** Files shared with the team (merged, not owned): when the agent is disabled, take only our part out. */
function renderDisabled(root: string, agents: AgentId[]): GeneratedFile[] {
  const out: GeneratedFile[] = [];
  const strip = (path: string, key: 'hooks') => {
    if (!existsSync(join(root, path))) return;
    const json = readJson(root, path);
    if (!json[key] || !JSON.stringify(json[key]).includes('sdlc hook')) return;
    json[key] = mergeHookMap(json[key], {});
    out.push({ path, content: JSON.stringify(json, null, 2) + '\n', merged: true });
  };
  if (!agents.includes('claude')) strip('.claude/settings.json', 'hooks');
  if (!agents.includes('cursor')) strip('.cursor/hooks.json', 'hooks');
  const agentsMd = join(root, 'AGENTS.md');
  if (!agents.includes('agents-md') && existsSync(agentsMd)) {
    const current = readFileSync(agentsMd, 'utf8');
    const i = current.indexOf(START);
    const j = current.indexOf(END);
    if (i >= 0 && j > i) out.push({ path: 'AGENTS.md', content: (current.slice(0, i).trimEnd() + '\n' + current.slice(j + END.length).trimStart()).trimStart(), merged: true });
  }
  return out;
}

export function renderProject(root: string, loaded: LoadedConfig): GeneratedFile[] {
  const locale = localeOf(loaded);
  const agents: AgentId[] = loaded.config.agents ?? ['claude'];
  const files = renderGitHooks();
  if (agents.includes('claude')) files.push(...renderClaude(root, loaded, locale));
  if (agents.some((a) => a !== 'claude')) files.push(...renderShared(locale));
  if (agents.includes('cursor')) files.push(...renderCursor(root, locale));
  if (agents.includes('agents-md')) files.push(...renderAgentsMd(root, loaded, locale));
  files.push(...renderDisabled(root, agents));
  return files;
}

// ---------- sync ----------

const MANIFEST = '.sdlc/generated.json';
const sha = (s: string) => createHash('sha256').update(s).digest('hex').slice(0, 16);

export interface SyncReport {
  written: string[];
  unchanged: string[];
  /** generated files edited by hand (kept; use --force to overwrite) */
  drift: string[];
  /** files that existed before sdlc and would be replaced (kept; use --force) */
  conflicts: string[];
  /** previously generated files no longer produced (e.g. an agent was disabled) and deleted */
  removed: string[];
  hooksPath?: { set: boolean; note?: string };
}

export function sync(root: string, loaded: LoadedConfig, opts: { force?: boolean; dryRun?: boolean } = {}): SyncReport {
  ensureSdlcDir(root);
  const manifestPath = join(root, MANIFEST);
  const manifest: Record<string, string> = existsSync(manifestPath) ? JSON.parse(readFileSync(manifestPath, 'utf8')) : {};
  const next: Record<string, string> = {};
  const report: SyncReport = { written: [], unchanged: [], drift: [], conflicts: [], removed: [] };

  const files = renderProject(root, loaded);
  const produced = new Set(files.map((f) => f.path));
  for (const [path, known] of Object.entries(manifest)) {
    if (produced.has(path)) continue;
    const full = join(root, path);
    if (!existsSync(full)) continue;
    if (!opts.force && sha(readFileSync(full, 'utf8')) !== known) {
      report.drift.push(path);
      next[path] = known;
      continue;
    }
    if (!opts.dryRun) {
      rmSync(full);
      for (let dir = dirname(full); dir.startsWith(root + '/') && readdirSync(dir).length === 0; dir = dirname(dir)) rmdirSync(dir);
    }
    report.removed.push(path);
  }

  for (const f of files) {
    const full = join(root, f.path);
    const exists = existsSync(full);
    const current = exists ? readFileSync(full, 'utf8') : undefined;
    if (current === f.content) {
      report.unchanged.push(f.path);
      if (!f.merged) next[f.path] = sha(f.content);
      continue;
    }
    if (exists && !f.merged && !opts.force) {
      const known = manifest[f.path];
      if (known && known !== sha(current!)) {
        report.drift.push(f.path);
        next[f.path] = known;
        continue;
      }
      if (!known) {
        report.conflicts.push(f.path);
        continue;
      }
    }
    if (!opts.dryRun) {
      mkdirSync(dirname(full), { recursive: true });
      writeFileSync(full, f.content);
      if (f.executable) chmodSync(full, 0o755);
    }
    report.written.push(f.path);
    if (!f.merged) next[f.path] = sha(f.content);
  }

  if (!opts.dryRun) {
    writeFileSync(manifestPath, JSON.stringify(next, null, 2) + '\n');
    report.hooksPath = installHooksPath(root);
    recordEvent(root, { type: 'sync', detail: `${report.written.length} written, ${report.removed.length} removed, ${report.drift.length} drift` });
  }
  return report;
}

/** Point git at .sdlc/git-hooks unless another hook manager (husky, lefthook) already owns hooksPath. */
function installHooksPath(root: string): { set: boolean; note?: string } {
  if (git(root, ['rev-parse', '--git-dir']) === undefined) return { set: false, note: 'not a git repository' };
  const current = git(root, ['config', '--local', 'core.hooksPath']);
  if (current && current !== '.sdlc/git-hooks') {
    return { set: false, note: `core.hooksPath is ${current}; call \`${BIN} hook pre-commit --agent git\` and \`pre-push\` from there` };
  }
  if (!current) git(root, ['config', '--local', 'core.hooksPath', '.sdlc/git-hooks']);
  return { set: true };
}

/** Generated files whose content no longer matches what sync wrote (edited by hand). */
export function detectDrift(root: string): string[] {
  const manifestPath = join(root, MANIFEST);
  if (!existsSync(manifestPath)) return [];
  const manifest: Record<string, string> = JSON.parse(readFileSync(manifestPath, 'utf8'));
  return Object.entries(manifest)
    .filter(([p, h]) => !existsSync(join(root, p)) || sha(readFileSync(join(root, p), 'utf8')) !== h)
    .map(([p]) => p);
}
