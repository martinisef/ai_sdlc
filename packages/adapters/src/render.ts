export interface GeneratedFile {
  path: string;
  content: string;
  executable?: boolean;
  /** merged into an existing file instead of owned by sdlc (never reported as drift) */
  merged?: boolean;
}

const SHIM = `#!/bin/sh
# Generated by \`sdlc sync\`. Finds the sdlc CLI for hooks; fails open (exit 0) when it is missing,
# so a fresh clone without node_modules is never locked out (\`sdlc doctor\` reports it).
here="$(cd "$(dirname "$0")/../.." && pwd)"
if [ -n "$SDLC_BIN" ]; then exec $SDLC_BIN "$@"; fi
if [ -x "$here/node_modules/.bin/sdlc" ]; then exec "$here/node_modules/.bin/sdlc" "$@"; fi
if command -v sdlc >/dev/null 2>&1; then exec sdlc "$@"; fi
echo "ai-sdlc: sdlc CLI not found (npm i -D @morsadev/sdlc); guardrail skipped" >&2
exit 0
`;

const BIN = '.sdlc/bin/sdlc';

