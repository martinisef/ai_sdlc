import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { test } from 'node:test';
import { addLearning, learningsSize, listLearnings, loadConfig } from '../src/index.ts';
import { repo } from './helpers.ts';

const CLAUDE = `# Claims
<!-- One page max. -->

## Commands
- Test: \`make test\`

## Things Claude gets wrong
<!-- Filled in through use. -->

## Notes
Keep this.
`;

test('learn: appends a dated line to the section, before the next heading, and says where it came from', () => {
  const root = repo();
  writeFileSync(join(root, 'CLAUDE.md'), CLAUDE);
  const r = addLearning(root, loadConfig(root), { text: '  Call a stock item a SKU,\n never a product. ', stage: 'spec', change: '2026-11-stock', today: '2026-11-16' });
  assert.deepEqual(r.files, ['CLAUDE.md']);
  const md = readFileSync(join(root, 'CLAUDE.md'), 'utf8');
  assert.match(md, /<!-- Filled in through use. -->\n- Call a stock item a SKU, never a product\. \(learned 2026-11-16, \/sdlc-spec 2026-11-stock\)\n\n## Notes\nKeep this\.\n$/);
  assert.deepEqual(listLearnings(root, loadConfig(root)), [
    { file: 'CLAUDE.md', line: 9, text: 'Call a stock item a SKU, never a product.', date: '2026-11-16', source: '/sdlc-spec 2026-11-stock' },
  ]);

  const again = addLearning(root, loadConfig(root), { text: 'call a stock item a sku — never a product', today: '2026-11-17' });
  assert.deepEqual(again, { text: 'call a stock item a sku — never a product', files: [], duplicateIn: ['CLAUDE.md'] });
  assert.equal(learningsSize(root), 1);
});

test('learn: creates the section (or the file) in the project locale, and refuses secrets and stories', () => {
  const root = repo({ version: 1, locale: 'es' });
  addLearning(root, loadConfig(root), { text: 'Usá las fixtures compartidas en los tests', today: '2026-11-16' });
  assert.equal(readFileSync(join(root, 'CLAUDE.md'), 'utf8'), '# CLAUDE.md\n\n## Cosas que Claude hace mal\n- Usá las fixtures compartidas en los tests (aprendido 2026-11-16)\n');
  assert.throws(() => addLearning(root, loadConfig(root), { text: 'use the key AKIAABCDEFGHIJKLMNOP for tests' }), /secret|secreto/i);
  assert.throws(() => addLearning(root, loadConfig(root), { text: 'x'.repeat(301) }), /at most 300/);
  assert.throws(() => addLearning(root, loadConfig(root), { text: 'ok', stage: 'spec; rm -rf' }), /--stage/);
  assert.throws(() => addLearning(root, loadConfig(root), { text: '   ' }), /usage/);
});

test('learn: AGENTS.md gets it outside the block sdlc sync owns, so a sync keeps it', () => {
  const root = repo({ version: 1, locale: 'en', agents: ['claude', 'agents-md'] });
  writeFileSync(join(root, 'CLAUDE.md'), CLAUDE);
  const block = '<!-- ai-sdlc:start (generated by `sdlc sync`; edit .sdlc/config.json instead) -->\n## Things Claude gets wrong\n- inside the block\n<!-- ai-sdlc:end -->';
  writeFileSync(join(root, 'AGENTS.md'), `# AGENTS.md\n\n${block}\n`);
  const r = addLearning(root, loadConfig(root), { text: 'Run the migrations check before the tests', today: '2026-11-16' });
  assert.deepEqual(r.files, ['CLAUDE.md', 'AGENTS.md']);
  const agents = readFileSync(join(root, 'AGENTS.md'), 'utf8');
  assert.equal(agents, `# AGENTS.md\n\n${block}\n\n## Things Claude gets wrong\n- Run the migrations check before the tests (learned 2026-11-16)\n`);
  addLearning(root, loadConfig(root), { text: 'Prefer table-driven tests', today: '2026-11-16' });
  assert.match(readFileSync(join(root, 'AGENTS.md'), 'utf8'), /before the tests \(learned 2026-11-16\)\n- Prefer table-driven tests \(learned 2026-11-16\)\n$/);
  assert.equal(listLearnings(root, loadConfig(root)).filter((l) => l.file === 'AGENTS.md').length, 2);
});
