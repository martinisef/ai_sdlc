// Regenerates src/gen/currencies.generated.ts from the ISO 4217 subset the library supports.
import { writeFileSync } from 'node:fs';

const CURRENCIES: Record<string, { minorUnits: number; symbol: string }> = {
  USD: { minorUnits: 2, symbol: '$' },
  EUR: { minorUnits: 2, symbol: '€' },
  ARS: { minorUnits: 2, symbol: '$' },
  JPY: { minorUnits: 0, symbol: '¥' },
  KWD: { minorUnits: 3, symbol: 'KD' },
};

const body = Object.entries(CURRENCIES)
  .map(([code, c]) => `  ${code}: { minorUnits: ${c.minorUnits}, symbol: ${JSON.stringify(c.symbol)} },`)
  .join('\n');
writeFileSync(
  new URL('../src/gen/currencies.generated.ts', import.meta.url),
  `// GENERATED by scripts/generate-currencies.ts — do not edit by hand.\nexport const CURRENCIES = {\n${body}\n} as const;\n\nexport type CurrencyCode = keyof typeof CURRENCIES;\n`,
);
