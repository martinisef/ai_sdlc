// Generates plugins/ai-sdlc (the Claude Code plugin) from content/. Never edit the plugin by hand.
import { chmodSync, cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { CLAUDE_PLUGIN_HINT, claudePluginHooks, loadAgents, loadSkills, renderText } from '@ai-native-sdlc/adapters';

// The plugin ships one language: `npm run build:plugin -- --locale es` for a Spanish-speaking marketplace.
const arg = process.argv.indexOf('--locale');
const locale = arg > 0 && process.argv[arg + 1] === 'es' ? 'es' : 'en';

const out = 'plugins/ai-sdlc';
const bundle = 'packages/cli/dist/sdlc.mjs';
if (!existsSync(bundle)) throw new Error(`${bundle} missing: run \`npm run build:cli\` first`);
const version = JSON.parse(readFileSync('packages/cli/package.json', 'utf8')).version as string;
const description =
  locale === 'es'
    ? 'Loop AI-native: intent → spec → plan → build → ship → maintain, con guardrails, setup guiado e integración con GitHub/GitLab/Bitbucket y Jira.'
    : 'AI-native loop: intent → spec → plan → build → ship → maintain, with guardrails, guided setup and GitHub/GitLab/Bitbucket and Jira integration.';

const write = (path: string, content: string, executable = false) => {
  const full = join(out, path);
  mkdirSync(dirname(full), { recursive: true });
  writeFileSync(full, content);
  if (executable) chmodSync(full, 0o755);
};

rmSync(out, { recursive: true, force: true });
for (const skill of loadSkills(locale)) {
  for (const f of skill.files) write(`skills/${skill.name}/${f.rel}`, renderText(f.content, { sdlc_hint: CLAUDE_PLUGIN_HINT[locale] }), f.executable);
}
for (const agent of loadAgents(locale)) write(`agents/${agent.name}.md`, agent.raw);
write('hooks/hooks.json', JSON.stringify(claudePluginHooks(locale), null, 2) + '\n');
write(
  '.claude-plugin/plugin.json',
  JSON.stringify(
    {
      name: 'ai-sdlc',
      version,
      description,
      author: { name: 'ai-native-sdlc' },
      homepage: 'https://github.com/martinisef/ai_sdlc#readme',
      repository: 'https://github.com/martinisef/ai_sdlc',
      license: 'Apache-2.0',
      keywords: ['sdlc', 'workflow', 'hooks', 'jira', 'github', 'gitlab', 'bitbucket'],
    },
    null,
    2,
  ) + '\n',
);
mkdirSync(join(out, 'bin'), { recursive: true });
cpSync(bundle, join(out, 'bin/sdlc.mjs'));
chmodSync(join(out, 'bin/sdlc.mjs'), 0o755);
// the bundled CLI looks for content/ next to bin/ (needed by `sdlc sync` / `sdlc init` from the plugin)
cpSync('content', join(out, 'content'), { recursive: true });
write('GENERATED.md', '# Generated\n\nThis directory is generated by `npm run build` from `content/` and `packages/`. Edit the sources, not these files.\n');

const mp = JSON.parse(readFileSync('.claude-plugin/marketplace.json', 'utf8'));
mp.plugins = mp.plugins.map((p: { name: string }) => (p.name === 'ai-sdlc' ? { ...p, description, version } : p));
writeFileSync('.claude-plugin/marketplace.json', JSON.stringify(mp, null, 2) + '\n');
console.log(`generated ${out} (v${version}, ${locale})`);
